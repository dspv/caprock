// fixtureDB creates an empty Hermes state.db in a temp dir and returns a
// writer on it (the test plays Hermes) and its path.
func fixtureDB(t *testing.T) (*sql.DB, string) {
	t.Helper()
	path := filepath.Join(t.TempDir(), "state.db")
	w, err := sql.Open("sqlite", "file:"+filepath.ToSlash(path)+"?_pragma=journal_mode(WAL)")
	if err != nil {
		t.Fatal(err)
	}
	w.SetMaxOpenConns(1)
	t.Cleanup(func() { _ = w.Close() })
	if _, err := w.ExecContext(context.Background(), hermesSchema); err != nil {
		t.Fatal(err)
	}
	return w, path
}
